#!/usr/bin/env node
/**
 * dsh-whale-tail 构建脚本：assets/ + src/ → lib/client.js
 *
 * 约束：客户端插件由 dsh-client-modules 的 bundle route 编成单个 JS 模块下发，
 * 没有静态资源路由，所以 PNG 必须在构建期内联成 base64。
 *
 * 零依赖，只用 node: 内置模块。
 *
 * 用法：
 *   node scripts/build.mjs            构建一次
 *   node scripts/build.mjs --check    只校验素材，不写产物（CI 用）
 *   node scripts/build.mjs --watch    监听 assets/ 与 src/，变更即重建
 */

import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { watch } from 'node:fs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = path.join(ROOT, 'assets');
const TEMPLATE = path.join(ROOT, 'src', 'client.template.js');
const TARGET = path.join(ROOT, 'lib', 'client.js');
const PLACEHOLDER = '__STATES_JSON__';
const SIZE_WARN_BYTES = 250 * 1024;

const EXIT = { OK: 0, ASSET: 1, SYNTAX: 2, IO: 3 };
const MIN_FRAME_MS = 20;
const MAX_FRAME_MS = 80;

function fail(code, message) {
  console.error(`\n[build] FAILED: ${message}`);
  process.exit(code);
}

/** 从 PNG 的 IHDR 直接读宽高，不引入图像库。 */
function pngSize(buf) {
  const SIG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (buf.length < 24 || !buf.subarray(0, 8).equals(SIG)) throw new Error('不是合法 PNG（签名不符）');
  if (buf.toString('latin1', 12, 16) !== 'IHDR') throw new Error('PNG 缺少 IHDR');
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

async function readManifest() {
  const file = path.join(ASSETS, 'manifest.json');
  let raw;
  try {
    raw = await readFile(file, 'utf8');
  } catch (err) {
    fail(EXIT.IO, `读不到 ${path.relative(ROOT, file)}（${err.message}）`);
  }
  let manifest;
  try {
    manifest = JSON.parse(raw);
  } catch (err) {
    fail(EXIT.ASSET, `manifest.json 不是合法 JSON：${err.message}`);
  }

  const { tile, states } = manifest;
  if (!Number.isInteger(tile) || tile <= 0) fail(EXIT.ASSET, 'manifest.tile 必须是正整数');
  if (!Array.isArray(states) || states.length === 0) fail(EXIT.ASSET, 'manifest.states 必须是非空数组');

  const seen = new Set();
  for (const s of states) {
    if (!/^[a-z0-9]+$/.test(String(s.key))) fail(EXIT.ASSET, `state.key 非法：${JSON.stringify(s.key)}`);
    if (seen.has(s.key)) fail(EXIT.ASSET, `state.key 重复：${s.key}`);
    seen.add(s.key);
    if (!Number.isInteger(s.frames) || s.frames <= 0) fail(EXIT.ASSET, `${s.key}: frames 必须是正整数`);
    if (!Number.isInteger(s.loopMs) || s.loopMs <= 0) fail(EXIT.ASSET, `${s.key}: loopMs 必须是正整数`);
    const perFrame = s.loopMs / s.frames;
    if (perFrame < MIN_FRAME_MS || perFrame > MAX_FRAME_MS) {
      fail(EXIT.ASSET, `${s.key}: 每帧 ${perFrame.toFixed(1)}ms 超出 ${MIN_FRAME_MS}–${MAX_FRAME_MS}ms 合理区间（loopMs 或 frames 填错了？）`);
    }
  }
  return manifest;
}

/** 读入、校验并编码所有精灵图。 */
async function collect(manifest) {
  const { tile, states } = manifest;
  const entries = [];
  for (const s of states) {
    const file = path.join(ASSETS, `${s.key}.png`);
    let buf;
    try {
      buf = await readFile(file);
    } catch (err) {
      fail(EXIT.IO, `读不到素材 ${path.relative(ROOT, file)}（${err.message}）`);
    }
    let size;
    try {
      size = pngSize(buf);
    } catch (err) {
      fail(EXIT.ASSET, `${s.key}.png: ${err.message}`);
    }
    const wantW = s.frames * tile;
    if (size.height !== tile) fail(EXIT.ASSET, `${s.key}.png 高度是 ${size.height}，应为 ${tile}（单帧边长）`);
    if (size.width !== wantW) fail(EXIT.ASSET, `${s.key}.png 宽度是 ${size.width}，应为 ${wantW}（= ${s.frames} 帧 × ${tile}px）`);
    entries.push({ key: s.key, frames: s.frames, loopMs: s.loopMs, bytes: buf.length, b64: buf.toString('base64') });
  }
  return entries;
}

function renderStates(entries) {
  const rows = entries.map((e) => `      { key: '${e.key}', frames: ${e.frames}, loopMs: ${e.loopMs}, b64: '${e.b64}' },`);
  return `[\n${rows.join('\n')}\n    ]`;
}

async function build({ write = true } = {}) {
  const started = Date.now();
  const manifest = await readManifest();
  const entries = await collect(manifest);

  let template;
  try {
    template = await readFile(TEMPLATE, 'utf8');
  } catch (err) {
    fail(EXIT.IO, `读不到 ${path.relative(ROOT, TEMPLATE)}（${err.message}）`);
  }
  const marks = template.split(PLACEHOLDER).length - 1;
  if (marks !== 1) fail(EXIT.ASSET, `模板里 ${PLACEHOLDER} 应出现 1 次，实际 ${marks} 次`);

  const version = JSON.parse(await readFile(path.join(ROOT, 'package.json'), 'utf8')).version;
  const body = template.replace(PLACEHOLDER, renderStates(entries));
  const totalB64 = entries.reduce((n, e) => n + e.b64.length, 0);
  const header = [
    '/* generated by scripts/build.mjs — do not edit this file.',
    ` * version ${version} · built ${new Date().toISOString()} · sha256 ${createHash('sha256').update(body).digest('hex').slice(0, 16)}`,
    ` * edit src/client.template.js and assets/ instead */`,
    '',
  ].join('\n');

  if (!write) {
    console.log(`[build] --check ok: ${entries.length} states, ${(totalB64 / 1024).toFixed(1)}KB base64`);
    return EXIT.OK;
  }

  const out = header + body;
  try {
    await writeFile(TARGET, out, 'utf8');
  } catch (err) {
    fail(EXIT.IO, `写不了 ${path.relative(ROOT, TARGET)}（${err.message}）`);
  }

  try {
    await execFileAsync(process.execPath, ['--check', TARGET]);
  } catch (err) {
    fail(EXIT.SYNTAX, `产物语法检查未通过：${(err.stderr || err.message).trim()}`);
  }

  const rows = entries.map((e) => `  ${e.key.padEnd(5)} ${String(e.frames).padStart(2)} 帧  ${String(e.loopMs).padStart(4)}ms  png ${String(e.bytes).padStart(6)}B  b64 ${String(e.b64.length).padStart(6)}字符`);
  console.log(['[build] states:', ...rows].join('\n'));
  const kb = (out.length / 1024).toFixed(1);
  console.log(`[build] wrote ${path.relative(ROOT, TARGET)}  ${out.length} bytes (${kb}KB)  ${Date.now() - started}ms`);
  if (out.length > SIZE_WARN_BYTES) {
    console.warn(`[build] WARN 产物 ${kb}KB 超过 ${(SIZE_WARN_BYTES / 1024).toFixed(0)}KB，考虑减帧或量化素材`);
  }
  return EXIT.OK;
}

const args = new Set(process.argv.slice(2));

if (args.has('--check')) {
  await build({ write: false });
} else {
  await build();

  if (args.has('--watch')) {
    console.log('[build] watching assets/ and src/ ...');
    let timer = null;
    const trigger = () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        try {
          build().catch((err) => console.error('[build] watch error:', err.message));
        } catch (err) {
          console.error('[build] watch error:', err.message);
        }
      }, 100);
    };
    for (const dir of [ASSETS, path.dirname(TEMPLATE)]) {
      try {
        watch(dir, { persistent: true }, trigger);
      } catch (err) {
        console.error(`[build] 无法监听 ${dir}：${err.message}`);
      }
    }
  }
}
